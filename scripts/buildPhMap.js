const rad = (d) => (d * Math.PI) / 180;
function mercProject([lng, lat]) {
  const x = (lng + 180) / 360;
  const sinLat = Math.sin(rad(lat));
  const y = 0.5 - Math.log((1 + sinLat) / (1 - sinLat)) / (4 * Math.PI);
  return [x, y];
}
function buildProjection(features, W, H, pad) {
  let minX=Infinity, minY=Infinity, maxX=-Infinity, maxY=-Infinity;
  function processRing(ring) { for (const c of ring) { const [px,py]=mercProject(c); if(px<minX)minX=px; if(px>maxX)maxX=px; if(py<minY)minY=py; if(py>maxY)maxY=py; } }
  function processGeom(g) { if(!g) return; if(g.type==="Polygon") g.coordinates.forEach(processRing); if(g.type==="MultiPolygon") g.coordinates.forEach(p=>p.forEach(processRing)); }
  features.forEach(f=>processGeom(f.geometry));
  const scale=Math.min((W-2*pad)/(maxX-minX),(H-2*pad)/(maxY-minY));
  const offX=(W-scale*(maxX-minX))/2-scale*minX;
  const offY=(H-scale*(maxY-minY))/2-scale*minY;
  return ([lng,lat])=>{ const [px,py]=mercProject([lng,lat]); return [+(px*scale+offX).toFixed(1),+(py*scale+offY).toFixed(1)]; };
}
function ringToPath(ring, proj) { return ring.map((c,i)=>{const[x,y]=proj(c);return(i===0?"M":"L")+x+" "+y;}).join(" ")+" Z"; }
function geomToPath(geom, proj) {
  if(!geom) return "";
  const parts=[];
  if(geom.type==="Polygon") geom.coordinates.forEach(r=>parts.push(ringToPath(r,proj)));
  if(geom.type==="MultiPolygon") geom.coordinates.forEach(poly=>poly.forEach(r=>parts.push(ringToPath(r,proj))));
  return parts.join(" ");
}
function fetchText(url) {
  return new Promise((res,rej)=>{
    const req=https.get(url,{headers:{"User-Agent":"barkadash/1.0"}},(r)=>{
      if(r.statusCode===301||r.statusCode===302) return fetchText(r.headers.location).then(res).catch(rej);
      if(r.statusCode!==200) return rej(new Error("HTTP "+r.statusCode+" for "+url));
      const chunks=[]; r.on("data",c=>chunks.push(c)); r.on("end",()=>res(Buffer.concat(chunks).toString("utf8"))); r.on("error",rej);
    }); req.on("error",rej);
  });
}
function normalizeId(name) {
  return (name||"").toLowerCase().replace(/^province of\s+/i,"").replace(/\s*\(.*?\)\s*/g,"").replace(/[^a-z0-9]+/g,"-").replace(/^-+|-+$/g,"");
}
